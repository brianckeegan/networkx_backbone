"""Export the shared reference datasets as plain CSV files.

The cross-implementation fixtures in ``tests/fixtures/`` are generated by
running R ``backbone`` (``scripts/make_reference_fixtures.R``) and ``netbone``
(``scripts/make_netbone_fixtures.py``) on exactly the same data that
``networkx`` ships.  This script writes that data to
``tests/fixtures/reference_inputs/`` so the generators do not depend on the
``networkx`` version installed next to R or netbone:

- ``les_miserables.csv``: the weighted Les Misérables co-appearance network
  (``source,target,weight``, one row per undirected edge).
- ``karate.csv``: Zachary's karate club (``source,target,weight``; the
  weights are the interaction counts that ``networkx`` ships).
- ``davis_southern_women.csv``: the women x events attendance matrix (women
  are the agents), with the women's names in the first column and the events
  as the header, rows and columns in ``networkx`` node order.

``tests/test_reference_implementations.py`` checks that these files still
match ``networkx``.

Usage::

    python scripts/export_reference_inputs.py
"""

import csv
from pathlib import Path

import networkx as nx

OUT = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "reference_inputs"


def davis_incidence():
    """Return ``(women, events, rows)`` of the Davis attendance matrix."""
    B = nx.davis_southern_women_graph()
    women = [n for n, d in B.nodes(data=True) if d["bipartite"] == 0]
    events = [n for n, d in B.nodes(data=True) if d["bipartite"] == 1]
    rows = [[int(B.has_edge(w, e)) for e in events] for w in women]
    return women, events, rows


def write_edges(G, path):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(["source", "target", "weight"])
        for u, v, w in G.edges(data="weight"):
            writer.writerow([u, v, w])


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    write_edges(nx.les_miserables_graph(), OUT / "les_miserables.csv")
    write_edges(nx.karate_club_graph(), OUT / "karate.csv")
    women, events, rows = davis_incidence()
    with open(
        OUT / "davis_southern_women.csv", "w", newline="", encoding="utf-8"
    ) as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(["woman", *events])
        for w, row in zip(women, rows):
            writer.writerow([w, *row])
    print(f"wrote reference inputs to {OUT}")


if __name__ == "__main__":
    main()
